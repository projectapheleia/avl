// Description:
// Apheleia Verification Library (AVL) Benchmark
//
// Create and send - the cost of building one transaction object and driving it
// onto the RTL. Nothing here is randomized; the values are a counter.
//
// This file is compiled unchanged by every flavour, and by every benchmark in
// the group - signals_001 through signals_064 all elaborate this same module and
// drive the first "+signals=<n>" of its signals. Doing it that way, rather than
// with a model per signal count, keeps the elaboration, the clock and the
// baseline identical across the sweep, so the only thing that changes from one
// benchmark to the next is how much the testbench does per clock edge.
//
// Clock and reset are generated by the cocotb testbench in
// ../cocotb/create_and_send.py, which also runs the iteration loop, so every
// flavour shares an identical harness. Only who builds the item and writes the
// signals differs, and that is the sole thing inside the `ifdef below.
//
// The checker is common to all of them: the values driven must advance every
// time, and signal i must carry i more than signal 0 does. That holds however
// many items were built, so it does not have to be kept in step with the
// testbench's own count.

`timescale 1ns/1ps

module create_and_send_bench #(
    // Signals the model carries - the largest count any benchmark in the group
    // asks for. See the note above on why they are all elaborated regardless. A
    // benchmark asking for more than this fails in the initial block below
    // rather than quietly driving fewer, so raise it if the sweep grows.
    parameter int unsigned SIGNALS = 64,
    parameter int unsigned WIDTH   = 32
) (
    input logic clk,
    input logic rst_n,
    // Driven by the cocotb testbench. The sv flavour leaves these alone and
    // drives an identical array from inside the module instead - it cannot
    // assign to its own inputs - so that one checker serves every flavour.
    input logic [WIDTH-1:0] d [0:SIGNALS-1]
);

    // Common to every flavour - lets the testbench confirm that all of them ran
    // for the same number of clock cycles.
    int unsigned cycles = 0;

    always @(posedge clk) begin
        if (!rst_n) begin
            cycles <= 0;
        end
        else begin
            cycles <= cycles + 1;
        end
    end

    // How many of the signals this benchmark uses.
    int unsigned signals = SIGNALS;

    // Cleared for the baseline run, which measures the harness on its own.
    bit          enable  = 1'b1;
    int unsigned burst   = 1;

    initial begin
        void'($value$plusargs("signals=%d", signals));
        void'($value$plusargs("randomize=%d", enable));
        void'($value$plusargs("burst=%d", burst));

        if (signals < 1 || signals > SIGNALS) begin
            $fatal(1, "+signals=%0d outside the 1 to %0d this model carries", signals, SIGNALS);
        end
    end

    // -----------------------------------------------------------------------
    // The signals the checker looks at.
    // -----------------------------------------------------------------------
`ifdef BENCH_SV
    logic [WIDTH-1:0] observed [0:SIGNALS-1];
`else
    wire  [WIDTH-1:0] observed [0:SIGNALS-1];

    genvar gi;
    generate
        for (gi = 0; gi < SIGNALS; gi++) begin : g_observe
            assign observed[gi] = d[gi];
        end
    endgenerate
`endif

    // -----------------------------------------------------------------------
    // Checker, common to every flavour. The testbench reads checked back at
    // the end of the run to confirm that the items really did reach the RTL.
    // -----------------------------------------------------------------------
    logic [WIDTH-1:0] last     = '0;
    logic [WIDTH-1:0] expected;
    int unsigned      checked  = 0;
    longint unsigned  checksum = 0;

    always @(posedge clk) begin
        if (!rst_n) begin
            last <= '0;
        end
        // The values driven start at one, so signal 0 being zero means the
        // testbench has not driven anything yet and there is nothing to check.
        // That saves a valid signal, which is a write the testbench would have
        // to make on top of the ones under measurement - at one signal, half
        // of what is being measured.
        else if (observed[0] != '0) begin
            if (!(observed[0] > last)) begin
                $fatal(1, "values did not advance : %0d after %0d", observed[0], last);
            end

            for (int unsigned i = 1; i < signals; i++) begin
                expected = observed[0] + i;
                if (observed[i] != expected) begin
                    $fatal(1, "signal %0d : expected %0d, got %0d", i, expected, observed[i]);
                end
            end

            last     <= observed[0];
            checked  <= checked + 1;
            checksum <= checksum + 64'(observed[0]);
        end
    end

`ifdef BENCH_SV
    // -----------------------------------------------------------------------
    // The work under test, in SystemVerilog - a fresh object per clock edge,
    // filled with incrementing values and driven onto the signals. No
    // randomization: this is what building and sending an item costs.
    // -----------------------------------------------------------------------

    class create_and_send_item;

        // Sized to what the benchmark asks for rather than to the model, so an
        // item costs what its own signal count costs and no more.
        bit [WIDTH-1:0] d [];

        function new(int unsigned n);
            d = new[n];
        endfunction

    endclass : create_and_send_item

    create_and_send_item item;
    int unsigned         sent = 0;

    always @(posedge clk) begin
        if (rst_n && enable) begin
            repeat (burst) begin
                // A fresh item per edge, the way a testbench builds a fresh
                // sequence item per transaction rather than refilling one.
                item = new(signals);

                for (int unsigned i = 0; i < signals; i++) begin
                    item.d[i] = sent + 1 + i;
                end

                // Non-blocking, so the checker above sees the item on the next
                // edge - which is when a cocotb write lands too, and keeps the
                // two flavours in step.
                for (int unsigned i = 0; i < signals; i++) begin
                    observed[i] <= item.d[i];
                end

                sent += 1;
            end
        end
    end
`endif

    final begin
        $display("BENCH_RESULT rtl signals=%0d checked=%0d checksum=%0d",
                 signals, checked, checksum);
    end

endmodule : create_and_send_bench
