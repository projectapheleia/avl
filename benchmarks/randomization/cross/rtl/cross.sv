// Description:
// Apheleia Verification Library (AVL) Benchmark
//
// Cross constraints - four variables whose legal values depend on each other,
// mixing arithmetic, bitwise and list constructs in a single solve.
//
// The dependency runs a -> b -> c -> d. "a" is anchored by a set, "b" is
// bounded relative to "a", "c" is built bitwise out of "a" and "b" and ordered
// against "b", and "d" is drawn from the set of the other three. Nothing here
// can be solved a variable at a time.
//
// This file is compiled unchanged by both flavours of the benchmark. Clock and
// reset are generated by the cocotb testbench in ../cocotb/cross.py, which also
// runs the iteration loop, so the two flavours share an identical harness.
//
// Only the randomization itself differs, and it is the sole thing inside the
// `ifdef below.
//
// The fields are 32 bits because Verilator 5.040 emits a malformed SMT-LIB
// expression for a right shift of a narrower vector - it passes a 32 bit shift
// constant to a 16 bit bvlshr - which the solver rejects, and the failure then
// poisons the solver connection for the rest of the simulation.

`timescale 1ns/1ps

module cross_bench (
    input logic clk,
    input logic rst_n
);

    // Common to both flavours - lets the testbench confirm that both ran for
    // the same number of clock cycles.
    int unsigned cycles = 0;

    always @(posedge clk) begin
        if (!rst_n) begin
            cycles <= 0;
        end
        else begin
            cycles <= cycles + 1;
        end
    end

`ifdef BENCH_SV_RANDOMIZE
    // -----------------------------------------------------------------------
    // Randomization under test - SystemVerilog classes and constraints.
    // -----------------------------------------------------------------------

    class cross_item;

        rand bit [31:0] a;
        rand bit [31:0] b;
        rand bit [31:0] c;
        rand bit [31:0] d;

        // List - anchors a to a set of ranges and a discrete value.
        constraint c_a { a inside {[32'd100:32'd200], [32'd1000:32'd1100], 32'd5000}; }

        // Arithmetic - b is bounded relative to a.
        constraint c_b { b > a;
                         b < a + 32'd1000; }

        // Arithmetic - c is ordered against b.
        constraint c_c { c > b; }

        // Bitwise - the bottom byte of c is the xor of a and b.
        constraint c_mask { (c & 32'h0000_00ff) == ((a ^ b) & 32'h0000_00ff); }

        // Bitwise and arithmetic - the top byte of c follows the top byte of a.
        constraint c_shift { (c >> 8) == ((a >> 8) + 32'd1); }

        // List - d is drawn from the other three fields.
        constraint c_d { d inside {a, b, c}; }

    endclass : cross_item

    cross_item       item;
    bit              enable   = 1'b1;
    int unsigned     burst    = 1;
    longint unsigned checksum = 0;
    int unsigned     count    = 0;

    initial begin
        item = new();
        // Cleared for the baseline run, which measures the harness on its own.
        void'($value$plusargs("randomize=%d", enable));
        void'($value$plusargs("burst=%d", burst));
    end

    always @(posedge clk) begin
        if (rst_n && enable) begin
            repeat (burst) begin
                if (item.randomize() == 0) begin
                    $fatal(1, "randomization failed on iteration %0d", count);
                end

                if (!(item.a inside {[32'd100:32'd200], [32'd1000:32'd1100], 32'd5000})) begin
                    $fatal(1, "c_a violated : a=%0d", item.a);
                end
                if (!(item.b > item.a && item.b < 32'(item.a + 32'd1000))) begin
                    $fatal(1, "c_b violated : a=%0d b=%0d", item.a, item.b);
                end
                if (!(item.c > item.b)) begin
                    $fatal(1, "c_c violated : b=%0d c=%0d", item.b, item.c);
                end
                if ((item.c & 32'h0000_00ff) != ((item.a ^ item.b) & 32'h0000_00ff)) begin
                    $fatal(1, "c_mask violated : a=%04x b=%04x c=%04x", item.a, item.b, item.c);
                end
                if ((item.c >> 8) != 32'((item.a >> 8) + 32'd1)) begin
                    $fatal(1, "c_shift violated : a=%04x c=%04x", item.a, item.c);
                end
                if (!(item.d inside {item.a, item.b, item.c})) begin
                    $fatal(1, "c_d violated : a=%0d b=%0d c=%0d d=%0d",
                           item.a, item.b, item.c, item.d);
                end

                checksum += 64'(item.a) + 64'(item.b) + 64'(item.c) + 64'(item.d);
                count    += 1;
            end
        end
    end

    final begin
        $display("BENCH_RESULT flavour=sv iterations=%0d checksum=%0d", count, checksum);
    end
`endif

endmodule : cross_bench
