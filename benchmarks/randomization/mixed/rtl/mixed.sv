// Description:
// Apheleia Verification Library (AVL) Benchmark
//
// Mixed constraints - the widest spread of constructs in the suite, on an item
// shaped like a real bus transaction. Ranges, sets, exclusion, alignment,
// bitwise masking, a shift, an implication, an if / else dependency and an
// inequality, over fields of four different widths.
//
// Where the other benchmarks isolate one category, this one is deliberately
// representative: it is the closest thing here to everyday constrained random
// code.
//
// This file is compiled unchanged by both flavours of the benchmark. Clock and
// reset are generated by the cocotb testbench in ../cocotb/mixed.py, which also
// runs the iteration loop, so the two flavours share an identical harness.
//
// Only the randomization itself differs, and it is the sole thing inside the
// `ifdef below.
//
// The address is 32 bits partly because Verilator 5.040 emits a malformed
// SMT-LIB expression for a right shift of a narrower vector - see the cross
// benchmark for the detail.

`timescale 1ns/1ps

module mixed_bench (
    input logic clk,
    input logic rst_n
);

    // Common to both flavours - lets the testbench confirm that both ran for
    // the same number of clock cycles.
    int unsigned cycles = 0;

    always @(posedge clk) begin
        if (!rst_n) begin
            cycles <= 0;
        end
        else begin
            cycles <= cycles + 1;
        end
    end

`ifdef BENCH_SV_RANDOMIZE
    // -----------------------------------------------------------------------
    // Randomization under test - SystemVerilog classes and constraints.
    // -----------------------------------------------------------------------

    class mixed_item;

        rand bit [31:0] addr;
        rand bit [15:0] len;
        rand bit [7:0]  kind;
        rand bit [7:0]  attr;
        rand bit        secure;

        // List - a set of discrete values.
        constraint c_kind { kind inside {8'd0, 8'd1, 8'd2, 8'd4, 8'd8}; }

        // Arithmetic - a bounded range.
        constraint c_len { len >= 16'd1;
                           len <= 16'd4096; }

        // Arithmetic - alignment, by modulo.
        constraint c_align { addr % 32'd4 == 32'd0; }

        // List - a window, with a reserved hole excluded from it.
        constraint c_addr { addr inside {[32'h1000_0000:32'h1fff_ffff]};
                            !(addr inside {[32'h1800_0000:32'h18ff_ffff]}); }

        // Bitwise - attr shares its low nibble with kind.
        constraint c_attr { (attr & 8'h0f) == (kind & 8'h0f); }

        // Bitwise - the page the address falls in, by shift.
        constraint c_page { (addr >> 24) inside {32'h10, 32'h11, 32'h1f}; }

        // Implication - one kind implies a single beat.
        constraint c_kind0 { (kind == 8'd0) -> (len == 16'd1); }

        // Dependency - if / else, so both branches are constrained.
        constraint c_secure { if (addr >= 32'h1f00_0000) secure == 1'b1;
                              else                       secure == 1'b0; }

        // Arithmetic - an inequality.
        constraint c_attr_ne { attr != 8'hff; }

    endclass : mixed_item

    mixed_item       item;
    bit              enable   = 1'b1;
    int unsigned     burst    = 1;
    longint unsigned checksum = 0;
    int unsigned     count    = 0;

    // Written only by the quality run, which is untimed - see +dump.
    int              dump_fd  = 0;
    string           dump_file;

    initial begin
        // Cleared for the baseline run, which measures the harness on its own.
        void'($value$plusargs("randomize=%d", enable));
        void'($value$plusargs("burst=%d", burst));

        if ($value$plusargs("dump=%s", dump_file)) begin
            dump_fd = $fopen(dump_file, "w");
            $fwrite(dump_fd, "addr:32,len:16,kind:8,attr:8,secure:1\n");
        end
    end

    always @(posedge clk) begin
        if (rst_n && enable) begin
            repeat (burst) begin
                // A fresh item per randomization, the way a testbench builds
                // a fresh sequence item per transaction, rather than one item
                // reused - which would let a solver amortize work across draws.
                item = new();

                if (item.randomize() == 0) begin
                    $fatal(1, "randomization failed on iteration %0d", count);
                end

                if (!(item.kind inside {8'd0, 8'd1, 8'd2, 8'd4, 8'd8})) begin
                    $fatal(1, "c_kind violated : kind=%0d", item.kind);
                end
                if (!(item.len >= 16'd1 && item.len <= 16'd4096)) begin
                    $fatal(1, "c_len violated : len=%0d", item.len);
                end
                if ((item.addr % 32'd4) != 32'd0) begin
                    $fatal(1, "c_align violated : addr=%08x", item.addr);
                end
                if (!(item.addr inside {[32'h1000_0000:32'h1fff_ffff]}) ||
                     (item.addr inside {[32'h1800_0000:32'h18ff_ffff]})) begin
                    $fatal(1, "c_addr violated : addr=%08x", item.addr);
                end
                if ((item.attr & 8'h0f) != (item.kind & 8'h0f)) begin
                    $fatal(1, "c_attr violated : kind=%02x attr=%02x", item.kind, item.attr);
                end
                if (!((item.addr >> 24) inside {32'h10, 32'h11, 32'h1f})) begin
                    $fatal(1, "c_page violated : addr=%08x", item.addr);
                end
                if ((item.kind == 8'd0) && (item.len != 16'd1)) begin
                    $fatal(1, "c_kind0 violated : len=%0d", item.len);
                end
                if (item.secure != ((item.addr >= 32'h1f00_0000) ? 1'b1 : 1'b0)) begin
                    $fatal(1, "c_secure violated : addr=%08x secure=%0b", item.addr, item.secure);
                end
                if (item.attr == 8'hff) begin
                    $fatal(1, "c_attr_ne violated : attr=%02x", item.attr);
                end

                if (dump_fd != 0) begin
                    $fwrite(dump_fd, "%0d,%0d,%0d,%0d,%0d\n", item.addr, item.len, item.kind, item.attr, item.secure);
                end

                checksum += 64'(item.addr) + 64'(item.len) + 64'(item.kind) +
                            64'(item.attr) + 64'(item.secure);
                count    += 1;
            end
        end
    end

    final begin
        if (dump_fd != 0) $fclose(dump_fd);
        $display("BENCH_RESULT flavour=sv iterations=%0d checksum=%0d", count, checksum);
    end
`endif

endmodule : mixed_bench
