// Description:
// Apheleia Verification Library (AVL) Benchmark
//
// Randomize and send - a whole transaction, end to end: build an object of 128
// constrained variables, randomize it, and drive the result onto the RTL, once
// per clock edge.
//
// This is the two halves of the tree in one measurement. The constraints are the
// bitwise ones of randomization/bitwise, rotated over the 128 variables, so what
// is being solved is a known quantity; the driving is what create_and_send
// measures at 128 signals. Neither half is separable here, and that is the point
// - it is the number a testbench actually pays per transaction.
//
// Clock and reset are generated by the cocotb testbench in
// ../cocotb/bitwise_128.py, which also runs the iteration loop, so every flavour
// shares an identical harness. Only who builds, randomizes and drives the item
// differs, and that is the sole thing inside the `ifdef below.
//
// The checker is common to every flavour: each signal must satisfy the
// constraint its position carries. Nothing else can be checked - the values are
// random - and nothing else needs to be, because a flavour that solved wrongly
// or drove nothing fails here.

`timescale 1ns/1ps

module bitwise_128_bench #(
    parameter int unsigned SIGNALS = 128,
    parameter int unsigned WIDTH   = 32
) (
    input logic clk,
    input logic rst_n,
    // Driven by the cocotb testbench. The sv flavour leaves these alone and
    // drives an identical array from inside the module instead - it cannot
    // assign to its own inputs - so that one checker serves every flavour.
    input logic [WIDTH-1:0] d [0:SIGNALS-1]
);

    // Common to every flavour - lets the testbench confirm that all of them ran
    // for the same number of clock cycles.
    int unsigned cycles = 0;

    always @(posedge clk) begin
        if (!rst_n) begin
            cycles <= 0;
        end
        else begin
            cycles <= cycles + 1;
        end
    end

    // How many of the signals this benchmark uses. Passed rather than assumed, so
    // that the count lives in bench.conf alongside the one the testbench reads.
    int unsigned signals = SIGNALS;

    // Cleared for the baseline run, which measures the harness on its own.
    bit          enable  = 1'b1;
    int unsigned burst   = 1;

    initial begin
        void'($value$plusargs("signals=%d", signals));
        void'($value$plusargs("randomize=%d", enable));
        void'($value$plusargs("burst=%d", burst));

        if (signals < 1 || signals > SIGNALS) begin
            $fatal(1, "+signals=%0d outside the 1 to %0d this model carries", signals, SIGNALS);
        end
    end

    // -----------------------------------------------------------------------
    // The signals the checker looks at.
    // -----------------------------------------------------------------------
`ifdef BENCH_SV
    logic [WIDTH-1:0] observed [0:SIGNALS-1];
`else
    wire  [WIDTH-1:0] observed [0:SIGNALS-1];

    genvar gi;
    generate
        for (gi = 0; gi < SIGNALS; gi++) begin : g_observe
            assign observed[gi] = d[gi];
        end
    endgenerate
`endif

    // -----------------------------------------------------------------------
    // Checker, common to every flavour. Each variable carries the constraint
    // its position gives it, the four rotating over the item. The testbench
    // reads checked back at the end of the run to confirm that the items really
    // did reach the RTL.
    // -----------------------------------------------------------------------
    int unsigned     checked  = 0;
    longint unsigned checksum = 0;

    always @(posedge clk) begin
        // Variable 0 carries c_0, which fixes its bottom byte to 5a, so it can
        // never be zero once it has been driven. That makes it the signal that
        // says whether anything has been driven at all, and saves a valid signal
        // - which would be a write the testbench had to make on top of the ones
        // under measurement.
        if (rst_n && observed[0] != '0) begin
            for (int unsigned i = 0; i < signals; i++) begin
                case (i % 4)
                    0: if ((observed[i] & 32'h0000_00ff) != 32'h0000_005a) begin
                           $fatal(1, "c_0 violated : d[%0d] = %h", i, observed[i]);
                       end
                    1: if ((observed[i] | 32'h0000_ffff) != 32'hffff_ffff) begin
                           $fatal(1, "c_1 violated : d[%0d] = %h", i, observed[i]);
                       end
                    2: if (((observed[i] ^ 32'ha5a5_a5a5) & 32'hffff_0000) != 32'h5a5a_0000) begin
                           $fatal(1, "c_2 violated : d[%0d] = %h", i, observed[i]);
                       end
                    3: if (((observed[i] >> 8) & 32'h0000_00ff) != 32'h0000_003c ||
                           observed[i][WIDTH-1:WIDTH-4] != 4'b1010) begin
                           $fatal(1, "c_3 violated : d[%0d] = %h", i, observed[i]);
                       end
                    default: ;
                endcase
            end

            checked  <= checked + 1;
            checksum <= checksum + 64'(observed[0]);
        end
    end

`ifdef BENCH_SV
    // -----------------------------------------------------------------------
    // The work under test, in SystemVerilog - a fresh object per clock edge,
    // randomized by the simulator's solver, then driven onto the signals.
    // -----------------------------------------------------------------------

    class bitwise_128_item;

        rand bit [WIDTH-1:0] d [SIGNALS];

        // The four bitwise constraints of randomization/bitwise, rotated over
        // the variables. One foreach per kind rather than a constraint per
        // variable, which is the same set of constraints written shorter.

        // Masked equality - fixes the bottom byte, leaves the rest free.
        constraint c_0 { foreach (d[i]) if (i % 4 == 0)
                             (d[i] & 32'h0000_00ff) == 32'h0000_005a; }

        // Or - forces the top half to all ones, leaves the bottom half free.
        constraint c_1 { foreach (d[i]) if (i % 4 == 1)
                             (d[i] | 32'h0000_ffff) == 32'hffff_ffff; }

        // Xor against a pattern, masked to the top half.
        constraint c_2 { foreach (d[i]) if (i % 4 == 2)
                             ((d[i] ^ 32'ha5a5_a5a5) & 32'hffff_0000) == 32'h5a5a_0000; }

        // Logical shift right, then masked equality, and a bit select.
        constraint c_3 { foreach (d[i]) if (i % 4 == 3) {
                             ((d[i] >> 8) & 32'h0000_00ff) == 32'h0000_003c;
                             d[i][WIDTH-1:WIDTH-4] == 4'b1010; } }

    endclass : bitwise_128_item

    bitwise_128_item item;
    int unsigned     sent = 0;

    always @(posedge clk) begin
        if (rst_n && enable) begin
            repeat (burst) begin
                // A fresh item per edge, the way a testbench builds a fresh
                // sequence item per transaction rather than refilling one.
                item = new();

                if (item.randomize() == 0) begin
                    $fatal(1, "randomization failed on iteration %0d", sent);
                end

                // Non-blocking, so the checker above sees the item on the next
                // edge - which is when a cocotb write lands too, and keeps the
                // flavours in step.
                for (int unsigned i = 0; i < signals; i++) begin
                    observed[i] <= item.d[i];
                end

                sent += 1;
            end
        end
    end
`endif

    final begin
        $display("BENCH_RESULT rtl signals=%0d checked=%0d checksum=%0d",
                 signals, checked, checksum);
    end

endmodule : bitwise_128_bench
