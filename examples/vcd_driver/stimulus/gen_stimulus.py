#!/usr/bin/env python3
# Copyright 2026 Apheleia
#
# Description:
# Writes adder.vcd, the capture the VCD driver examples replay.
#
# The file stands in for a waveform captured from somewhere else - an earlier
# simulation, another testbench, a logic analyser. It records a 50 MHz clock,
# an active low reset, the adder's three inputs and - as any capture of a
# running design would - its two outputs, for a hundred additions with idle
# cycles scattered between them. The inputs change on the falling edge of the
# clock, half a cycle before the rising edge that samples them, so that there
# is no question which value each cycle saw: replaying the capture with its own
# clock (timed) and replaying it cycle for cycle on a testbench clock (clocked)
# must give the DUT the same hundred additions. The outputs change on the
# rising edge, as the adder's registers do; the examples leave them to the DUT.
#
# Deterministic: running it again writes the same file.
#
#   python3 gen_stimulus.py [output.vcd]

import os
import random
import sys

PERIOD_NS = 20
RESET_CYCLES = 2
N_ITEMS = 100
IDLE_PROBABILITY = 0.2
TRAILING_CYCLES = 4
SEED = 1

# Inputs every adder should see, placed among the random ones
CORNERS = [(0, 0), (255, 255), (255, 1), (1, 255), (128, 128), (0, 255), (255, 0), (127, 127)]


def schedule(rng: random.Random) -> list[tuple[int, int, int, int]]:
    """
    One (rst_n, valid_in, a, b) per clock cycle.
    """
    cycles = [(0, 0, 0, 0)] * RESET_CYCLES

    items = CORNERS + [(rng.randrange(256), rng.randrange(256)) for _ in range(N_ITEMS - len(CORNERS))]
    rng.shuffle(items)

    for a, b in items:
        # Idle cycles carry junk on a and b: valid_in is low, so the adder must ignore them
        while rng.random() < IDLE_PROBABILITY:
            cycles.append((1, 0, rng.randrange(256), rng.randrange(256)))
        cycles.append((1, 1, a, b))

    cycles += [(1, 0, 0, 0)] * TRAILING_CYCLES
    return cycles


def outputs(cycles: list[tuple[int, int, int, int]]) -> list[tuple[int, int]]:
    """
    The adder's (valid_out, c) after the rising edge of each cycle - what a capture of the design records.
    """
    result = []
    valid_out, c = 0, 0
    for rst_n, valid_in, a, b in cycles:
        if not rst_n:
            valid_out, c = 0, 0
        else:
            valid_out = valid_in
            if valid_in:
                c = a + b
        result.append((valid_out, c))
    return result


def write_vcd(filename: str, cycles: list[tuple[int, int, int, int]]) -> None:
    half = PERIOD_NS // 2
    codes = {"clk": "!", "rst_n": '"', "valid_in": "#", "a": "$", "b": "%", "valid_out": "&", "c": "'"}
    widths = {"clk": 1, "rst_n": 1, "valid_in": 1, "a": 8, "b": 8, "valid_out": 1, "c": 9}
    outs = outputs(cycles)

    def change(name: str, value: int) -> str:
        if widths[name] == 1:
            return f"{value}{codes[name]}"
        return f"b{value:b} {codes[name]}"

    lines = [
        "$date",
        "    generated by gen_stimulus.py",
        "$end",
        "$version",
        "    AVL VCD driver example",
        "$end",
        f"$timescale {1}ns $end",
        "$scope module adder $end",
    ]
    for name in codes:
        rng_txt = "" if widths[name] == 1 else f" [{widths[name] - 1}:0]"
        lines.append(f"$var wire {widths[name]} {codes[name]} {name}{rng_txt} $end")
    lines += ["$upscope $end", "$enddefinitions $end"]

    # Initial state is the first cycle's inputs with the clock low
    rst_n, valid_in, a, b = cycles[0]
    lines += ["#0", "$dumpvars", change("clk", 0), change("rst_n", rst_n), change("valid_in", valid_in), change("a", a), change("b", b), change("valid_out", 0), change("c", 0), "$end"]

    previous = cycles[0]
    previous_out = (0, 0)
    for k, current in enumerate(cycles):
        t = k * PERIOD_NS
        if k:
            # Falling edge: the inputs for this cycle settle here, half a cycle before they are sampled
            lines.append(f"#{t}")
            lines.append(change("clk", 0))
            for name, old, new in zip(("rst_n", "valid_in", "a", "b"), previous, current, strict=True):
                if new != old:
                    lines.append(change(name, new))
        # Rising edge: the registers take their new values here
        lines.append(f"#{t + half}")
        lines.append(change("clk", 1))
        for name, old, new in zip(("valid_out", "c"), previous_out, outs[k], strict=True):
            if new != old:
                lines.append(change(name, new))
        previous = current
        previous_out = outs[k]

    lines.append(f"#{len(cycles) * PERIOD_NS}")
    lines.append(change("clk", 0))

    with open(filename, "w") as f:
        f.write("\n".join(lines) + "\n")


def main() -> None:
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "adder.vcd")
    cycles = schedule(random.Random(SEED))
    write_vcd(out, cycles)
    n_valid = sum(1 for rst_n, valid_in, _, _ in cycles if rst_n and valid_in)
    print(f"{out}: {len(cycles)} cycles, {n_valid} additions, {len(cycles) * PERIOD_NS} ns")


if __name__ == "__main__":
    main()
